#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Format scraped foodcourt.com.ua recipes into Telegram post_text.
#
# Uses Claude CLI with skills from apps/automation and examples from recipes.json.
# Writes progress to recipes_formatted.json after every batch of 20 recipes.
#
# Usage:
#   ./scripts/format-posts.sh
#   BATCH_SIZE=10 ./scripts/format-posts.sh
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
DATASETS_DIR="$ROOT_DIR/apps/pipeline/additional-data/datasets/recipes"
SCRAPED_FILE="$DATASETS_DIR/recipes_scraped.json"
OUTPUT_FILE="$DATASETS_DIR/recipes_formatted.json"
BATCH_SIZE="${BATCH_SIZE:-20}"

echo "Formatting recipe posts for Telegram"
echo "  Input:  $SCRAPED_FILE"
echo "  Output: $OUTPUT_FILE"
echo "  Batch:  $BATCH_SIZE recipes per write"
echo ""

# ── Read skills from automation project ──────────────────────────────────────

ANTI_SLOP=$(cat "$ROOT_DIR/apps/automation/src/common/ai/skills/anti-slop.skill.ts" \
  | sed "s/^export.*$//" | grep -A 200 'instructions:' | head -60)

HUMAN_VOICE=$(cat "$ROOT_DIR/apps/automation/src/common/ai/skills/human-voice.skill.ts" \
  | sed "s/^export.*$//" | grep -A 200 'instructions:' | head -60)

RECIPES_CHANNEL=$(cat "$ROOT_DIR/apps/automation/src/common/ai/skills/recipes-channel.skill.ts" \
  | sed "s/^export.*$//" | grep -A 200 'instructions:' | head -60)

# ─────────────────────────────────────────────────────────────────────────────

PROMPT="Ти агент-форматувальник рецептів для Telegram каналу.
Твоя задача: відкрити файл зі скрапленими рецептами і сформувати post_text для кожного рецепту.

## SKILLS — обов'язкові правила стилю

### Anti-AI Writing Rules
${ANTI_SLOP}

### Human Voice Rules
${HUMAN_VOICE}

### Recipes Channel Rules
${RECIPES_CHANNEL}

## ФОРМАТ post_text

Структура кожного поста:
\`\`\`
<b>Назва страви</b>

Інгредієнти одним рядком через кому, коротко (без зайвих «штука», «кількість»).

Кроки приготування коротко — 2-4 речення, активний стан (готуємо, нарізаємо, додаємо).

Одна конкретна нотатка про страву (час, техніка, результат) — або пропусти якщо нема що додати.

#рецепт #категорія #тег1 #тег2
\`\`\`

Правила:
- Довжина: намагайся вмістити у 1024 символи (caption ліміт Telegram). Для складних рецептів — до 4048.
- HTML тільки <b></b> для назви.
- Теги: #рецепт завжди першим, далі #категорія, потім 2-3 теги зі списку tags рецепту (через підкреслення).
- Мова: виключно українська.
- Активний стан: «ріжемо», «додаємо», «запікаємо» — не «нарізається», «додається».

## ПРИКЛАДИ (10 готових рецептів)

Приклад 1:
<b>Гострий гаспачо</b>

Помідори 1200 г, солодкий перець, халапеньо, батон 2 скибочки, часник 2 зубчики, фіолетова цибулина, томатний сік 200–300 мл, оливкова олія 2 ст. л., червоний винний оцет 60 мл, сіль, перець.

Нарізаємо овочі й батон, збиваємо в блендері до пюре. Додаємо сік, олію, оцет, сіль і перець. Охолоджуємо 1,5–2 години в холодильнику. Подаємо з нарізаними овочами, зеленню або авокадо.

Активна робота — 15 хвилин, далі холодильник робить все сам.

#рецепт #супи #гаспачо #вегетаріанське

---

Приклад 2:
<b>В'єтнамський суп Фо Бо</b>

Яловичі кістки 3 кг, вода 6 л, цибуля 2 шт., імбир, кориця 2 палички, коріандр 1 ст. л., аніс 6 зірочок, гвоздика 6 шт., рибний соус 50 мл, цукор 2 ч. л., рисова локшина 450 г, філе яловичини 250 г, фіолетова цибуля, петрушка, чилі.

Кістки відварюємо, зливаємо першу воду. Заливаємо 6 л свіжої води, додаємо обпалену цибулю й імбир. Спеції підсмажуємо на сухій сковороді 2 хвилини, кладемо в бульйон. Варимо 3 години, проціджуємо, додаємо рибний соус і цукор.

У тарілку кладемо зварену локшину й тонко нарізане сире філе. Заливаємо киплячим бульйоном — м'ясо доходить у тарілці. Подаємо з чилі та зеленню.

#рецепт #супи #фобо #в'єтнамська_кухня

---

Приклад 3:
<b>Салат цезар з беконом</b>

Хліб 2–3 скибочки, оливкова олія 1 ст. л., пармезан 50–60 г, бекон 4 скибочки, сметана 4 ст. л., діжонська гірчиця 1 ч. л., вустерський соус ½ ч. л., часник ½ зубчика, лимон ½ шт., ромен 1 качан.

Хліб кубиками збризкуємо олією, посипаємо сіллю і половиною пармезану — запікаємо при 180°C 10 хвилин. Бекон підсмажуємо на сухій сковороді. Змішуємо сметану з гірчицею, вустерським соусом, часником, лимонним соком і рештою пармезану. Рвемо салат руками, заправляємо соусом, додаємо бекон і грінки.

Сметана замість майонезу дає легшу кислувату заправку.

#рецепт #салати #цезар #20хвилин

---

Приклад 4:
<b>Рулетики з листкового тіста з шинкою та сиром</b>

Листкове тісто 250 г, шинка 150 г, твердий сир 150 г, яйце 1 шт.

Розкочуємо тісто прямокутним пластом. Натираємо сир і шинку на тертці, розподіляємо по тесту. Згортаємо рулетом з широкого краю, нарізаємо шматками по 1 см. Викладаємо на лист з папером, змащуємо збитим яйцем. Випікаємо при 180°C 20–25 хвилин.

#рецепт #закуски #сніданок #листкове_тісто

---

Приклад 5:
<b>Салат з капустою, зеленою цибулею та огірками</b>

Огірки 2 шт., капуста 400 г, зелена цибуля 70 г, рослинна олія 50 мл, оцет 6% 30 мл, сіль, перець, петрушка.

Шаткуємо капусту, нарізаємо огірки і рубаємо зелену цибулю — все змішуємо. Готуємо заправку: олія плюс оцет. Поливаємо, солимо, перчимо, додаємо петрушку.

#рецепт #салати #капуста #вегетаріанське #5хвилин

---

Приклад 6:
<b>Прості вафлі на кефірі</b>

Кефір 200 мл, яйце 1 шт., ванільний цукор 1 ч. л., цукор 2–3 ст. л., борошно 150 г, сіль 1 щіпка, сода ½ ч. л., розпушувач 1 ч. л., вершкове масло 50 г.

Збиваємо кефір, яйце і цукор до однорідності. Просіюємо борошно з сіллю, содою і розпушувачем у рідку суміш, перемішуємо. Розтоплюємо масло і вливаємо в тісто. Випікаємо у вафельниці 4–5 хвилин до золотистого кольору.

Тісто готується за 5 хвилин із звичайних продуктів.

#рецепт #вафлі #сніданок #десерти

---

Приклад 7:
<b>Тонкі яблучні млинці на молоці</b>

Молоко 500 мл, яйця 2 шт., цукор 1¼ ст. л., ванільний цукор 10 г, сіль 1 щіпка, кориця ½ ч. л., борошно 180 г, рослинна олія 30 мл, яблука 2 шт.

З'єднуємо молоко, яйця, цукор, сіль і корицю. Додаємо борошно, вливаємо олію. Натираємо яблука на великій тертці, додаємо в тісто. Смажимо млинці на змащеній сковороді з двох боків до підрум'янення.

Яблука в тісті дають кислинку і аромат — начинка не потрібна.

#рецепт #млинці #сніданок #яблука #десерти

---

Приклад 8:
<b>Сендвічі з яйцями та консервованою горбушею</b>

Яйця 2–3 шт., консервована горбуша 1 банка, зелень, майонез 1 ст. л., сіль, перець, хліб для тостів 4–6 скибочок.

Відварюємо яйця круто, натираємо на тертці. Зливаємо рідину з консерви, розминаємо рибу виделкою. Дрібно рубаємо зелень. Змішуємо рибу, яйця, зелень, майонез, сіль і перець. Підсмажуємо хліб у тостері. Викладаємо начинку між скибочками.

#рецепт #сніданок #сендвіч #риба #10хвилин

---

Приклад 9:
<b>Грецький салат із фетою</b>

Помідори черрі 350 г, огірки 1–2 шт., фета 70–100 г, лимон ½ шт., червоний винний оцет 2 ст. л., оливкова олія 3 ст. л., орегано ½ ч. л., оливки 150–180 г, сіль, перець, зелень.

Черрі ріжемо навпіл, огірки — шматочками, фету кришимо. Змішуємо лимонний сік, оцет, олію та орегано. Складаємо овочі з фетою й оливками, поливаємо заправкою, солимо, перчимо.

Готується за 10 хвилин. Заправка з оцтом і лимоном дає кислинку, яка добре балансує солоність фети.

#рецепт #салати #грецький_салат #вегетаріанське

---

Приклад 10:
<b>Салат з авокадо, креветками та гірчичною заправкою</b>

Креветки 450–500 г, авокадо 2 шт., салат 1 пучок, лайми 3 шт., йогурт 120 г, майонез 2 ст. л., пармезан 30–50 г, діжонська гірчиця 1 ч. л., сіль, перець.

Відварюємо й очищаємо креветки, остуджуємо. Авокадо ріжемо шматочками, рвемо салат руками. Вичавлюємо сік із 3 лаймів, змішуємо з йогуртом, майонезом, пармезаном, гірчицею, сіллю й перцем. Складаємо все в салатник, поливаємо заправкою.

#рецепт #салати #авокадо #креветки #вечеря

## ІНСТРУКЦІЇ

1. Прочитай файл: ${SCRAPED_FILE}

2. Обробляй рецепти порціями по ${BATCH_SIZE} штук.

3. Для кожного рецепту:
   - Якщо ingredients і instructions порожні — залиш post_text як порожній рядок (це стаття, не рецепт).
   - Інакше — згенеруй post_text за правилами вище.

4. Після кожної порції з ${BATCH_SIZE} рецептів — ЗРАЗУ записуй увесь накопичений масив до файлу: ${OUTPUT_FILE}
   Формат файлу:
   {
     \"source\": \"foodcourt.com.ua\",
     \"formatted_at\": \"<ISO date>\",
     \"total\": <кількість всіх рецептів>,
     \"processed\": <кількість оброблених (з непорожнім post_text)>,
     \"recipes\": [ ...всі 423 рецепти, оброблені мають post_text, решта — порожній рядок... ]
   }

5. Продовжуй до кінця файлу.

6. Після завершення виведи: 'DONE: X recipes formatted, saved to ${OUTPUT_FILE}'

ВАЖЛИВО:
- Записуй у файл після КОЖНОЇ порції, щоб не втратити прогрес.
- Не вигадуй інгредієнти чи кроки — тільки те, що є в полях ingredients та instructions.
- Кожен post_text унікальний — не копіюй між рецептами."

echo "Starting Claude CLI agent..."
echo ""

claude -p "$PROMPT" \
  --allowedTools "Read,Write" \
  --model sonnet \
  --max-turns 120

echo ""
echo "Checking output..."

if [ -f "$OUTPUT_FILE" ]; then
  TOTAL=$(node -e "const d=JSON.parse(require('fs').readFileSync('$OUTPUT_FILE','utf-8')); console.log(d.total||d.recipes.length)")
  PROCESSED=$(node -e "const d=JSON.parse(require('fs').readFileSync('$OUTPUT_FILE','utf-8')); console.log(d.processed||(d.recipes.filter(r=>r.post_text).length))")
  echo "Result: ${PROCESSED}/${TOTAL} recipes with post_text in $OUTPUT_FILE"
else
  echo "Output file not found."
  exit 1
fi
