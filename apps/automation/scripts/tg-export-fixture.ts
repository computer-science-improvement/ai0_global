/**
 * Spec 037 FR-001: regenerate the golden-set fixture from Telegram Desktop HTML exports (offline, no DB, no network).
 *
 *   npx tsx scripts/tg-export-fixture.ts "<export dir or folder of export dirs>" [more…] [--out <file.json>]
 *
 * Default output: src/editor/post/testing/channel-logs-2026-10.json. Only the parsed posts are written (text, links,
 * buttons, hashtags, media kind/count, polls); never images or raw HTML. The labels file next to it is hand-kept:
 * after a regeneration, check that every post id still has a row (golden-set.test.ts fails on a missing one).
 */
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { findExportDirs, parseTelegramExportDir } from '../src/editor/post/integrity/tg-export';

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
const out = outAt >= 0 ? resolve(args[outAt + 1]) : join(__dirname, '../src/editor/post/testing/channel-logs-2026-10.json');
const paths = outAt >= 0 ? args.filter((_a, i) => i !== outAt && i !== outAt + 1) : args;
if (!paths.length) {
  console.error('usage: tsx scripts/tg-export-fixture.ts <export dir | folder of export dirs> […] [--out file.json]');
  process.exit(2);
}

const dirs = findExportDirs(paths);
const channels = dirs.map((d) => parseTelegramExportDir(d, { timezone: 'Europe/Kyiv' }));
const posts = channels.flat();
const fixture = {
  about: 'Spec 037 golden set: the three DEV channels (AI Шукає Новини, AI Технології, Біржа Ігор), Telegram Desktop export '
    + '07–14.10.2026. Generated by scripts/tg-export-fixture.ts; posts only (album parts merged into their post, see messageIds).',
  messages: posts.reduce((n, p) => n + (p.messageIds?.length ?? 1), 0),
  channels: channels.map((ps) => ({ channel: ps[0]?.channel ?? '', posts: ps.length })),
  posts,
};
writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`${posts.length} posts (${fixture.messages} messages) from ${dirs.length} export(s) → ${out}`);
for (const c of fixture.channels) console.log(`  ${c.channel}: ${c.posts}`);
